"""조수사 사전. 고유어 읽기(세 개) / 한자어 읽기(삼 층) 중 어느 쪽이 쓰이는지.
사전에 없는 조수사는 두 읽기를 모두 후보로 넣는다 (틀리게 감점하는 것보다 관대한 쪽이 안전)."""

NATIVE = {
    "개", "명", "시", "시간", "살", "마리", "번째", "잔", "병", "권", "그루",
    "송이", "사람", "켤레", "벌", "채", "척", "통", "자루", "줄", "곳", "군데", "가지", "달",
    "끼", "판", "조각", "알", "포기", "다발", "봉지", "상자", "컵", "접시", "쌍", "팀", "배",
    "편", "곡", "줄기",
    # 아래는 두 읽기가 다 쓰여서 SINO에도 넣는다: 세 개월/삼 개월, 세 번/삼 번 출구, 세 점/삼 점, 세 동/삼 동, 세 대/삼 대, 세 장/삼 장, 세 쪽/삼 쪽
    "개월", "번", "점", "동", "대", "장", "쪽",
}
SINO = {
    "층", "원", "년", "월", "일", "호", "초", "세", "도", "퍼센트", "미터", "킬로미터", "킬로그램",
    "그램", "리터", "번지", "학년", "반", "페이지", "교시", "차", "회", "주", "세기",
    "등", "위", "인분", "인", "호선", "분기", "단계", "차선", "번길", "급", "차례",
    "개월", "번", "점", "동", "대", "장", "쪽",
}
# 둘 다에 있으면 lookup은 None(둘 다 허용)으로 처리된다
_BOTH = NATIVE & SINO
MAX_LEN = max(map(len, NATIVE | SINO))


def lookup(following: str):
    """숫자 뒤에 오는 글자들에서 가장 긴 조수사를 찾아 'native' | 'sino' | None 반환."""
    for n in range(min(MAX_LEN, len(following)), 0, -1):
        word = following[:n]
        if word in _BOTH:
            return None
        if word in NATIVE:
            return "native"
        if word in SINO:
            return "sino"
    return None
